/**
 * Printing and PDF export.
 *
 * Printing goes through an offscreen `BrowserWindow` rather than the main
 * window. That matters for three reasons:
 *
 *  - the main window keeps its scroll position and never shows a preview flash;
 *  - the printed document loads its own minimal HTML, so app state cannot leak
 *    into the page;
 *  - `webContents.printToPDF` gives a real PDF file for WhatsApp or email
 *    without a PDF library.
 *
 * The HTML arrives from the renderer and is therefore untrusted input: it is
 * rendered in a window with Node disabled, no preload script, and navigation and
 * new windows blocked. `data:` navigation is used precisely because it cannot
 * reach the network.
 */

import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { BrowserWindow, dialog, shell } from "electron";
import type { Logger } from "./logger";
import { META_CONTENT_SECURITY_POLICY } from "../shared/content-security-policy";

export type PaperSize = "A4" | "A5" | "Letter" | "thermal80";

export interface PrintOptions {
  readonly silent: boolean;
  readonly paperSize: PaperSize;
  readonly landscape: boolean;
  readonly copies: number;
}

/**
 * The paper size Electron is given.
 *
 * The named sizes are used rather than a width and height because Electron
 * rejects a custom size below 352, and A4 in inches is 8.27. The document's
 * own `@page` rule decides the size and the orientation in the end: Chromium
 * prefers the CSS page size over the option, so one rule in one place decides
 * whether a report prints portrait or landscape.
 */
const PAPER_NAMES: Record<PaperSize, "A4" | "A5" | "Letter"> = {
  A4: "A4",
  A5: "A5",
  Letter: "Letter",
  thermal80: "A4",
};

/**
 * No electronic margins.
 *
 * The margin is part of the document's `@page` rule, which is what makes the
 * preview and the printed page identical. Setting a margin here as well would
 * add the two together.
 */
const NO_MARGINS = { top: 0, bottom: 0, left: 0, right: 0 };

export interface PrintOutcome {
  readonly printed: boolean;
  readonly path: string | null;
}

/**
 * Render HTML in a sandboxed offscreen window.
 *
 * The window is destroyed in a `finally` so a failed print cannot leak a hidden
 * window that keeps the process alive.
 */
async function withDocument<T>(
  html: string,
  run: (contents: BrowserWindow["webContents"]) => Promise<T>,
): Promise<T> {
  const window = new BrowserWindow({
    show: false,
    webPreferences: {
      nodeIntegration: false,
      contextIsolation: true,
      sandbox: true,
      javascript: false,
      webSecurity: true,
      // No preload: the printed document is inert markup, so the window has no
      // privileged surface to expose.
    },
  });

  try {
    window.webContents.setWindowOpenHandler(() => ({ action: "deny" }));
    window.webContents.on("will-navigate", (event) => {
      event.preventDefault();
    });

    // A meta tag is the only CSP that applies to a data: document.
    const guarded = injectCsp(html);

    await window.loadURL(`data:text/html;charset=utf-8,${encodeURIComponent(guarded)}`);
    // Yield once so layout and any webfonts settle before the print snapshot.
    await new Promise((resolve) => setTimeout(resolve, 60));

    return await run(window.webContents);
  } finally {
    if (!window.isDestroyed()) window.destroy();
  }
}

/**
 * Add the CSP meta tag if the document does not already declare one.
 *
 * Print documents are generated by us, but they embed user-entered text
 * (customer names, notes). A restrictive policy means that text can never become
 * executable markup even if it contains something that looks like a tag.
 */
function injectCsp(html: string): string {
  if (/<meta[^>]+http-equiv=["']Content-Security-Policy/i.test(html)) return html;

  const meta = `<meta http-equiv="Content-Security-Policy" content="${META_CONTENT_SECURITY_POLICY}">`;

  if (/<head[^>]*>/i.test(html)) {
    return html.replace(/<head[^>]*>/i, (match) => `${match}${meta}`);
  }
  if (/<html[^>]*>/i.test(html)) {
    return html.replace(/<html[^>]*>/i, (match) => `${match}<head>${meta}</head>`);
  }
  return meta + html;
}

/**
 * Chromium's own page footer.
 *
 * Chromium has no CSS page counter, so the page number has to come from its
 * footer template. It is drawn inside the page's bottom margin, which the
 * document leaves room for, so it never lands on top of the report.
 *
 * The same template is used for the printed page and for the exported PDF, so
 * the two carry the same running title and the same page numbers.
 */
function pageFooterTemplate(label: string): string {
  const escaped = label
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

  return (
    '<div style="width:100%;font-size:8px;font-family:Segoe UI,Helvetica,Arial,sans-serif;' +
    "padding:0 12mm;color:#64748b;display:flex;justify-content:space-between;align-items:center;\">" +
    `<span>${escaped}</span>` +
    "<span>Page&nbsp;<span class=\"pageNumber\"></span>&nbsp;of&nbsp;<span class=\"totalPages\"></span></span>" +
    "<span></span></div>"
  );
}

/** Send the document to the system printer (or silently, for "Save as PDF"). */
export async function printHtml(
  html: string,
  options: PrintOptions,
  log: Logger,
  footerLabel = "",
): Promise<PrintOutcome> {
  try {
    await withDocument(html, async (contents) => {
      await new Promise<void>((resolve, reject) => {
        contents.print(
          {
            silent: options.silent,
            printBackground: true,
            copies: options.copies,
            landscape: options.landscape,
            pageSize: PAPER_NAMES[options.paperSize],
            margins: NO_MARGINS,
            // Chromium draws this in the page's bottom margin, below the
            // document, so it cannot overlap the report.
            footer: pageFooterTemplate(footerLabel),
          },
          (success, reason) => {
            if (success) {
              resolve();
              return;
            }
            // "cancelled" is a user choice, not a failure to report loudly.
            if (reason === "cancelled" || reason === "Print job canceled") {
              resolve();
              return;
            }
            reject(new Error(reason));
          },
        );
      });
    });

    log.info("Document sent to printer", { paperSize: options.paperSize, silent: options.silent });
    return { printed: true, path: null };
  } catch (error) {
    log.error("Print failed", {
      error: error instanceof Error ? error.message : String(error),
    });
    throw new Error("Could not print. Check the printer is switched on and try again.");
  }
}

/** Write the document to a PDF file chosen by the user. */
export async function saveHtmlAsPdf(
  html: string,
  suggestedName: string,
  exportsDir: string,
  log: Logger,
  footerLabel = "",
): Promise<string> {
  const result = await dialog.showSaveDialog({
    title: "Save as PDF",
    defaultPath: join(
      exportsDir,
      suggestedName.endsWith(".pdf") ? suggestedName : `${suggestedName}.pdf`,
    ),
    filters: [{ name: "PDF", extensions: ["pdf"] }],
  });

  if (result.canceled || result.filePath === undefined) {
    throw new Error("cancelled");
  }

  const pdf = await withDocument(html, (contents) =>
    contents.printToPDF({
      printBackground: true,
      // The document's own `@page` rule decides the paper, including whether
      // the report is portrait or landscape.
      preferCSSPageSize: true,
      margins: NO_MARGINS,
      displayHeaderFooter: true,
      headerTemplate: "<div></div>",
      footerTemplate: pageFooterTemplate(footerLabel),
    }),
  );

  await writeFile(result.filePath, pdf);

  log.info("PDF written", { path: result.filePath, bytes: pdf.length });
  return result.filePath;
}

/**
 * Open a URL in the OS browser.
 *
 * Only https and mailto are permitted. This is the one place the app reaches
 * the network, it is entirely user-initiated (a WhatsApp link, a mailto), and
 * it never loads anything into the app window.
 */
export function openExternalSafely(url: string, log: Logger): { opened: boolean } {
  try {
    const parsed = new URL(url);

    if (parsed.protocol !== "https:" && parsed.protocol !== "mailto:") {
      log.warn("Refused to open external URL with unsafe scheme", { url });
      return { opened: false };
    }

    void shell.openExternal(url);
    return { opened: true };
  } catch {
    log.warn("Refused to open malformed external URL", { url });
    return { opened: false };
  }
}
