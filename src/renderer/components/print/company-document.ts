/**
 * The company block that heads every document, and the shell they share.
 *
 * The company details come from Settings and from nowhere else. A printed
 * invoice, a report and a printed product record must all say the same thing
 * about the business, so they all read the same snapshot and render it through
 * the same function. Nothing here is hardcoded: a field the shopkeeper has not
 * filled in is left out rather than filled with a placeholder.
 */

import type { AppSettingsSnapshot } from "../../../shared/ipc";
import { documentCss, type DocumentOrientation } from "./document-css";
import { escapeHtml, joinParts, toLines } from "./html";

/** The business details a document header needs. */
export interface CompanyProfile {
  readonly name: string;
  readonly addressLines: readonly string[];
  readonly phone: string;
  readonly email: string;
  readonly registrationNumber: string;
  readonly logoDataUrl: string | null;
}

/**
 * Read the company details out of the settings snapshot.
 *
 * The logo is a `data:` URL derived by the main process from the file the
 * shopkeeper chose; the printed document runs in a sandboxed window with no
 * filesystem access, so the bytes have to travel with it.
 */
export function companyProfile(
  settings: AppSettingsSnapshot,
  logoDataUrl?: string | null,
): CompanyProfile {
  return {
    // The application name is the honest fallback: it says who produced the
    // document without inventing a business that does not exist.
    name: settings.companyName.trim().length > 0 ? settings.companyName.trim() : "EyerStock",
    addressLines: toLines(settings.companyAddress),
    phone: settings.companyPhone.trim(),
    email: settings.companyEmail.trim(),
    registrationNumber: settings.companyTrn.trim(),
    logoDataUrl: logoDataUrl ?? settings.companyLogoDataUrl,
  };
}

/** The company block, laid out with the logo beside the details. */
export function renderCompanyHeader(
  profile: CompanyProfile,
  title: string,
  subtitle?: string,
): string {
  const logo =
    profile.logoDataUrl === null
      ? ""
      : `<img class="doc-logo" src="${escapeHtml(profile.logoDataUrl)}" alt="" />`;

  const contact = joinParts(
    [
      profile.phone.length > 0 ? profile.phone : null,
      profile.email.length > 0 ? profile.email : null,
    ],
    " · ",
  );

  return `
    <header class="doc-header">
      <div class="doc-identity">
        ${logo}
        <div>
          <div class="doc-company-name">${escapeHtml(profile.name)}</div>
          ${
            profile.addressLines.length > 0
              ? `<div class="doc-company-meta">${profile.addressLines
                  .map((line) => `<span>${escapeHtml(line)}</span>`)
                  .join("")}</div>`
              : ""
          }
          ${contact.length > 0 ? `<div class="doc-company-meta">${escapeHtml(contact)}</div>` : ""}
          ${
            profile.registrationNumber.length > 0
              ? `<div class="doc-company-meta"><span>TRN ${escapeHtml(profile.registrationNumber)}</span></div>`
              : ""
          }
        </div>
      </div>
      <div class="doc-heading">
        <div class="doc-title">${escapeHtml(title)}</div>
        ${subtitle === undefined || subtitle.length === 0 ? "" : `<div class="doc-subtitle">${escapeHtml(subtitle)}</div>`}
        <div class="doc-subtitle">Amounts in PKR</div>
      </div>
    </header>
    <div class="doc-rule"></div>`;
}

/** Attribution printed on every document the app produces. */
export const GENERATED_BY = "Generated by EyerStock";
export const POWERED_BY = "Powered by Eyercall";

export interface DocumentFooterOptions {
  /** The document's own name, shown on the left of the footer. */
  readonly label: string;
  /** Anything else worth repeating at the foot of the page. */
  readonly detail?: string | undefined;
}

/**
 * The footer block.
 *
 * It sits at the end of the document. The page number and the running title
 * come from Chromium's own page footer, which is drawn in the page's bottom
 * margin and so cannot land on top of the report.
 */
export function renderDocumentFooter(options: DocumentFooterOptions): string {
  const detail = options.detail ?? "";
  const left = joinParts([options.label, detail], " · ");

  return `
    <div class="doc-footer">
      <span>${escapeHtml(left)}</span>
      <span class="doc-footer-brand">${escapeHtml(GENERATED_BY)} · ${escapeHtml(POWERED_BY)}</span>
    </div>`;
}

/**
 * The document information strip.
 *
 * Every document carries the same facts about itself: what it covers, the
 * moment it was produced, and who produced it. They sit under the header so a
 * printed page is never anonymous.
 */
export function renderDocumentInfo(
  blocks: readonly { readonly label: string; readonly value: string }[],
  generatedAt: Date,
): string {
  const all = [...blocks, { label: "Generated", value: formatTimestamp(generatedAt) }];

  return `
    <div class="doc-info">
      ${all
        .map(
          (block) => `
        <div class="doc-info-block">
          <div class="doc-label">${escapeHtml(block.label)}</div>
          <div class="doc-value">${escapeHtml(block.value)}</div>
        </div>`,
        )
        .join("")}
      <div class="doc-info-block">
        <div class="doc-label">Prepared by</div>
        <div class="doc-value">${escapeHtml(`${GENERATED_BY} · ${POWERED_BY}`)}</div>
      </div>
    </div>`;
}

/** The moment a document was produced, in the format the app uses everywhere. */
export function formatTimestamp(when: Date): string {
  return new Intl.DateTimeFormat("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(when);
}

export interface DocumentShellOptions {
  /** Document title, used in the header and in the browser tab. */
  readonly title: string;
  /** Secondary line under the title. */
  readonly subtitle?: string | undefined;
  /** The company details to print. */
  readonly profile: CompanyProfile;
  /** The body of the document. */
  readonly body: string;
  /** Paper orientation. */
  readonly orientation?: DocumentOrientation | undefined;
  /** Extra markup placed between the header rule and the body. */
  readonly info?: string | undefined;
  /** The label used in the footer. */
  readonly footerLabel?: string | undefined;
  /** Extra text for the footer's left-hand side. */
  readonly footerDetail?: string | undefined;
}

/**
 * Wrap a body in the shared document shell.
 *
 * The header, the divider, the attribution footer and the stylesheet are the
 * same for every document, so they are built once here. The title and subtitle
 * are substituted into the header after the fact because the header is also
 * used on its own by the preview.
 */
export function renderDocumentShell(options: DocumentShellOptions): string {
  const orientation = options.orientation ?? "portrait";
  const profile = options.profile;

  const header = renderCompanyHeader(profile, options.title, options.subtitle);

  const info = options.info ?? "";
  const footerLabel = options.footerLabel ?? options.title;

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>${escapeHtml(options.title)}</title>
    <style>${documentCss(orientation)}</style>
  </head>
  <body>
    ${header}
    ${info}
    ${options.body}
    ${renderDocumentFooter({ label: footerLabel, detail: options.footerDetail })}
  </body>
</html>`;
}
