test.describe("Printing", () => {
  /**
   * Capture what the printer is actually handed.
   *
   * The renderer hands the document to the main process over the print
   * channel, so replacing that handler captures the exact document that would
   * have gone to the paper.
   */
  async function installPrintCapture(): Promise<void> {
    await testApp.app.evaluate(({ ipcMain }) => {
      const store = globalThis as unknown as { __printed?: string[] };
      store.__printed = [];

      ipcMain.removeHandler("print:document");
      ipcMain.handle("print:document", (_event, payload: unknown) => {
        const target = globalThis as unknown as { __printed?: string[] };
        const html = (payload as { html?: string }).html ?? "";
        target.__printed = [...(target.__printed ?? []), html];
        return { ok: true, data: "printed" };
      });
    });
  }

  async function capturedPrints(): Promise<string[]> {
    return testApp.app.evaluate(() => {
      const store = globalThis as unknown as { __printed?: string[] };
      return store.__printed ?? [];
    });
  }

  test("printing an invoice shows the A4 page first, then hands it to the printer", async () => {
    const partyId = await seedParty("customer", "Marina View Hotel");
    const invoice = await rpc<{ id: number; number: string }>(testApp.window, "documents.save", {
      kind: "invoice",
      partyId,
      issueDate: TODAY,
      status: "issued",
      lines: [
        {
          productId: null,
          description: "Inline UV steriliser, 40 GPM",
          quantityMilli: 2_000,
          unitPriceFils: 245_000,
          vatTreatment: "standard",
        },
      ],
    });

    await navigateTo(testApp.window, /^sales$/i);
    const row = testApp.window.getByRole("row", { name: new RegExp(invoice.number) });
    await row.waitFor({ state: "visible", timeout: 30_000 });

    await installPrintCapture();
    await row.getByRole("button", { name: /row actions/i }).click();
    await testApp.window.getByRole("menuitem", { name: /^print$/i }).click();

    // The preview opens before anything reaches the printer.
    const dialog = testApp.window.getByRole("dialog");
    await dialog.waitFor({ state: "visible", timeout: 20_000 });
    await expect(dialog.getByText(/a4/i).first()).toBeVisible();
    await expect(dialog.getByRole("button", { name: /^print$/i })).toBeVisible();
    await expect(dialog.getByRole("button", { name: /save pdf/i })).toBeVisible();

    // The preview holds the document itself.
    const preview = dialog.locator('iframe[title="Document preview"]');
    await preview.waitFor({ state: "visible", timeout: 20_000 });
    const frame = testApp.window.frameLocator('iframe[title="Document preview"]');
    await expect(frame.getByText("Blue Water Trading").first()).toBeVisible();
    await expect(frame.getByText(invoice.number).first()).toBeVisible();

    // Nothing has been printed yet.
    expect(await capturedPrints()).toHaveLength(0);

    // Now the printer gets it.
    await dialog.getByRole("button", { name: /^print$/i }).click();
    await expect
      .poll(async () => (await capturedPrints()).length, { timeout: 20_000 })
      .toBeGreaterThan(0);

    const printed = await capturedPrints();
    const html = printed[0] ?? "";

    // The company's own details are on the document.
    expect(html).toContain("Blue Water Trading");
    // And so is the record's own data.
    expect(html).toContain(invoice.number);
    expect(html).toContain("Marina View Hotel");
    expect(html).toContain("Inline UV steriliser, 40 GPM");
    // And the attribution the app is required to print.
    expect(html).toContain("Generated by EyerStock");
    expect(html).toContain("Powered by Eyercall");
    // And nothing from the application around it.
    expect(html).not.toContain("Sidebar");
    expect(html).not.toContain("New product");
  });

  test("printing a product shows the A4 page before it reaches the printer", async () => {
    await seedProduct("Inline UV steriliser", "ITM-00001");
    await navigateTo(testApp.window, /^products$/i);

    const row = testApp.window.getByRole("row", { name: /Inline UV steriliser/i });
    await row.waitFor({ state: "visible", timeout: 30_000 });

    await installPrintCapture();
    await row.getByRole("button", { name: /row actions/i }).click();
    await testApp.window.getByRole("menuitem", { name: /^print$/i }).click();

    const dialog = testApp.window.getByRole("dialog");
    await dialog.waitFor({ state: "visible", timeout: 20_000 });

    // The sheet is A4: 210 by 297 millimetres.
    const sheet = dialog.locator("iframe[title='Document preview']");
    await sheet.waitFor({ state: "visible", timeout: 20_000 });
    const frame = testApp.window.frameLocator('iframe[title="Document preview"]');
    await expect(frame.getByText("Blue Water Trading").first()).toBeVisible();
    await expect(frame.getByText(/reference cost/i)).toBeVisible();

    // Nothing has been printed yet.
    expect(await capturedPrints()).toHaveLength(0);

    await dialog.getByRole("button", { name: /^print$/i }).click();
    await expect
      .poll(async () => (await capturedPrints()).length, { timeout: 20_000 })
      .toBeGreaterThan(0);

    const html = (await capturedPrints())[0] ?? "";
    expect(html).toContain("Blue Water Trading");
    expect(html).toContain("Inline UV steriliser");
    expect(html).toContain("Generated by EyerStock");
  });

  test("printing a report hands the printer the generated document", async () => {
    await navigateTo(testApp.window, /^reports$/i);
    await testApp.window
      .getByRole("button", { name: /profit & loss/i })
      .first()
      .click();
    await testApp.window.getByRole("button", { name: /generate report/i }).click();
    await testApp.window.locator('iframe[title$="preview"]').waitFor({ timeout: 30_000 });

    await installPrintCapture();
    await testApp.window.getByRole("button", { name: /print report/i }).click();
    await expect
      .poll(async () => (await capturedPrints()).length, { timeout: 20_000 })
      .toBeGreaterThan(0);

    const printed = await capturedPrints();
    const html = printed[0] ?? "";

    expect(html).toContain("Blue Water Trading");
    expect(html).toContain("Profit and Loss");
    expect(html).toContain("Generated by EyerStock");
    expect(html).toContain("Powered by Eyercall");
  });
});

