import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { expect, test } from "@playwright/test";
import { completeSetup, launchApp, navigateTo, rpc, type TestApp, todayIso } from "./app";

/**
 * The reporting and print upgrade, end to end.
 *
 * These run against the real application: the reports are generated from the
 * live database, the preview is the document the printer receives, and the
 * record actions are the ones the row menus actually offer.
 */

let testApp: TestApp;

const TODAY = todayIso();

/**
 * The built renderer must ship every file it asks for.
 *
 * A file that is referenced but missing is not a visible error: the window
 * simply comes up blank, or comes up in the wrong palette, because the script
 * that was supposed to run before the first paint never arrived. This check
 * reads the built output, which is what the application actually ships.
 */
test("the built renderer ships every file it asks for", () => {
  const rendererDir = join(process.cwd(), "dist", "renderer");
  const html = readFileSync(join(rendererDir, "index.html"), "utf8");

  const referenced = [...html.matchAll(/(?:src|href)="\.?\/?([^"]+)"/g)]
    .map((match) => match[1] ?? "")
    .filter((value) => value.length > 0 && !value.startsWith("http"));

  expect(referenced.length).toBeGreaterThan(0);

  const missing = referenced.filter(
    (value) => !existsSync(join(rendererDir, value)) && !existsSync(join(rendererDir, "assets", value)),
  );

  expect(missing).toEqual([]);
});

