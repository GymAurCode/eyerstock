    await navigateTo(testApp.window, /^reports$/i);
    await testApp.window
      .getByRole("button", { name: /sales report/i })
      .first()
      .click();
    await testApp.window.getByRole("button", { name: /generate report/i }).click();

    // The preview is an iframe holding the very document the printer gets.
    const preview = testApp.window.locator('iframe[title$="preview"]');
    await preview.waitFor({ state: "visible", timeout: 30_000 });

    const frame = testApp.window.frameLocator('iframe[title$="preview"]');
