    await expect(frame.getByText("Powered by Eyercall").first()).toBeVisible();
    await expect(frame.getByText("Amounts in PKR")).toBeVisible();
    await expect(frame.getByText(/MARINA VIEW HOTEL/i).first()).toBeVisible();

    // The report actions are offered.
    await expect(testApp.window.getByRole("button", { name: /print report/i })).toBeVisible();
    await expect(testApp.window.getByRole("button", { name: /export pdf/i })).toBeVisible();
    await expect(testApp.window.getByRole("button", { name: /back to reports/i })).toBeVisible();

    // The generated timestamp is the moment of generation, not a fixed date.
    const generated = frame.getByText(/^\d{2} \w{3} \d{4}, \d{2}:\d{2}$/).first();
    await expect(generated).toBeVisible();
