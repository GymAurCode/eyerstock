/**
 * License key generation and checking.
 *
 * The logic behind the `npm run keygen*` commands, with no argument parsing and
 * nothing that runs on import, so the test suite can drive it directly.
 *
 * Keys are built and checked with `src/main/license-verify.ts` - the same
 * module the app verifies with, against the same public key constant that is
 * compiled into the app. Re-implementing the format here is what previously let
 * the generator and the app disagree about which bytes were signed.
 */

import { generateKeyPairSync, createPublicKey } from "node:crypto";
import { writeFileSync, readFileSync, existsSync, chmodSync } from "node:fs";
import { join } from "node:path";

import {
  checkLicenseStages,
  createLicenseKey,
  decodeLicensePayload,
  splitLicenseKey,
  verifyLicense,
  type LicensePayload,
} from "../../src/main/license-verify";

export const PRIVATE_KEY_FILE = join(__dirname, "private.key");
export const PUBLIC_KEY_CONSTANT_FILE = join(
  __dirname,
  "..",
  "..",
  "src",
  "main",
  "license-public-key.ts",
);

// ============================================================================
// Keypair
// ============================================================================

/** The public key the shipped app verifies with, read out of the source file. */
export function readEmbeddedPublicKeyPem(): string | null {
  try {
    const content = readFileSync(PUBLIC_KEY_CONSTANT_FILE, "utf8");
    const match = /LICENSE_PUBLIC_KEY = "([^"]+)"/.exec(content);
    if (match?.[1] === undefined) return null;
    return Buffer.from(match[1], "base64").toString("utf8").trim();
  } catch {
    return null;
  }
}

/** Write the public key into the constant the app compiles in. */
export function writeEmbeddedPublicKey(publicKeyPem: string): void {
  const publicKeyB64 = Buffer.from(publicKeyPem, "utf8").toString("base64");
  writeFileSync(
    PUBLIC_KEY_CONSTANT_FILE,
    `/**
 * Ed25519 public key for license verification.
 *
 * AUTO-GENERATED BY keygen:init - DO NOT EDIT MANUALLY.
 * Run \`npm run keygen:init\` to regenerate.
 */

export const LICENSE_PUBLIC_KEY = "${publicKeyB64}";
`,
    "utf8",
  );
}

/** The public key that belongs to the private key on disk. */
export function derivePublicKeyPem(privateKeyPem: string): string {
  return createPublicKey(privateKeyPem).export({ type: "spki", format: "pem" }).toString().trim();
}

export function privateKeyExists(): boolean {
  return existsSync(PRIVATE_KEY_FILE);
}

export function loadPrivateKey(): string {
  if (!privateKeyExists()) {
    throw new Error(
      `Private key not found at ${PRIVATE_KEY_FILE}. Run \`npm run keygen:init\` first.`,
    );
  }
  return readFileSync(PRIVATE_KEY_FILE, "utf8").trim();
}

/**
 * Fail loudly when the keypair has drifted apart.
 *
 * `keygen:init` writes both files, so they normally agree. They stop agreeing
 * when the private key is replaced without the constant being rewritten, when a
 * build picks up a stale `license-public-key.ts`, or when one of the two files
 * is copied around on its own. Every key produced from that point on is
 * correctly signed and useless: the app holds a different public key and
 * reports "signature does not match" for a key that was never edited.
 */
export function assertKeypairMatches(): string {
  const embedded = readEmbeddedPublicKeyPem();
  if (embedded === null) {
    throw new Error(
      `No public key found in ${PUBLIC_KEY_CONSTANT_FILE}. Run \`npm run keygen:init\` first.`,
    );
  }

  const derived = derivePublicKeyPem(loadPrivateKey());
  if (derived !== embedded) {
    console.error("");
    console.error("  ERROR: private.key does not match the public key embedded in the app.");
    console.error("");
    console.error(`    private key : ${PRIVATE_KEY_FILE}`);
    console.error(`    public key  : ${PUBLIC_KEY_CONSTANT_FILE}`);
    console.error("");
    console.error("  Every key signed with this private key will be REJECTED by the app.");
    console.error("");
    console.error("  To rewrite the public key constant to match the private key:");
    console.error("    npm run keygen:init -- --force");
    console.error("");
    console.error("  If you meant to start a new keypair, back up the existing");
    console.error("  private.key first - keys already issued with it stop working.");
    console.error("");
    throw new Error("Keypair mismatch: private.key does not match LICENSE_PUBLIC_KEY.");
  }

  return embedded;
}

/** Rewrite only the public key constant, from the private key already on disk. */
export function syncPublicKeyToPrivateKey(): string {
  const derived = derivePublicKeyPem(loadPrivateKey());
  writeEmbeddedPublicKey(derived);
  return derived;
}

export interface GenerateKeypairOptions {
  /** Replace an existing private key. Without it, an existing key is refused. */
  readonly force: boolean;
}

export interface GenerateKeypairResult {
  readonly created: boolean;
  readonly reason?: string;
}

/**
 * Create a keypair and write both halves.
 *
 * Generating a new private key silently invalidates every key already sold, so
 * an existing key is refused unless `force` is set. Callers are expected to have
 * warned the user by then; this is the backstop that stops a stray `npm run
 * keygen:init` from doing it.
 */
export function generateKeypair(options: GenerateKeypairOptions): GenerateKeypairResult {
  if (privateKeyExists() && !options.force) {
    return {
      created: false,
      reason: `A private key already exists at ${PRIVATE_KEY_FILE}.`,
    };
  }

  const { privateKey, publicKey } = generateKeyPairSync("ed25519", {
    privateKeyEncoding: { type: "pkcs8", format: "pem" },
    publicKeyEncoding: { type: "spki", format: "pem" },
  });

  writeFileSync(PRIVATE_KEY_FILE, privateKey, { mode: 0o600 });
  // Windows ignores the POSIX mode and a checkout can reset it, so set it
  // explicitly for platforms that do honour it.
  try {
    chmodSync(PRIVATE_KEY_FILE, 0o600);
  } catch {
    // Best effort: a failure here must not stop the keypair being written.
  }

  writeEmbeddedPublicKey(publicKey.toString());

  return { created: true };
}

// ============================================================================
// Key generation
// ============================================================================

export interface BuildLicenseKeyOptions {
  readonly machine: string;
  readonly client: string;
  readonly expires?: string | undefined;
  readonly edition?: string | undefined;
  readonly privateKeyPem?: string | undefined;
  readonly publicKeyPem?: string | undefined;
}

/**
 * Issue a key.
 *
 * Every key is verified through the app's own code path - same module, same
 * public key, same machine binding - before it is returned. A key that does not
 * survive that is never shown to anyone, rather than being discovered to be
 * worthless by the customer it was sold to.
 */
export function buildLicenseKey(options: BuildLicenseKeyOptions): string {
  const privateKeyPem = options.privateKeyPem ?? loadPrivateKey();
  const publicKeyPem = options.publicKeyPem ?? assertKeypairMatches();

  const payload: LicensePayload = {
    machineId: options.machine,
    clientName: options.client,
    issuedAt: new Date().toISOString(),
    expiresAt: options.expires ? new Date(`${options.expires}T23:59:59.999Z`).toISOString() : null,
    edition: options.edition ?? "standard",
  };

  const key = createLicenseKey(payload, privateKeyPem);

  const check = verifyLicense({ key, publicKeyPem, machineId: options.machine });
  if (!check.ok) {
    throw new Error(`Generated key failed self-verification at the "${check.stage}" check.`);
  }

  return key;
}

// ============================================================================
// Key verification
// ============================================================================

export interface VerifyCommandOptions {
  readonly key: string;
  /** When given, the machine binding is checked too. */
  readonly machine?: string | undefined;
  readonly publicKeyPem?: string | undefined;
}

export interface VerifyCommandResult {
  readonly ok: boolean;
  readonly stage: string;
  readonly message: string | null;
  readonly payload: LicensePayload | null;
  readonly daysUntilExpiry: number | null;
  /** One row per check, so the caller can print them all. */
  readonly checks: readonly {
    readonly name: string;
    readonly passed: boolean;
    readonly detail: string;
  }[];
}

/**
 * Check a key with the app's own code, reporting each stage separately.
 *
 * A key can fail more than one check at once - wrong computer and expired, say -
 * so every stage is reported rather than stopping at the first failure.
 */
export function verifyLicenseCommand(options: VerifyCommandOptions): VerifyCommandResult {
  const publicKeyPem = options.publicKeyPem ?? assertKeypairMatches();

  const result = verifyLicense({
    key: options.key,
    publicKeyPem,
    machineId: options.machine ?? null,
  });

  // Every stage is evaluated on its own. Reading "machineId failed, expiry
  // passed" off a single short-circuiting result would report an expired key as
  // perfectly valid in date, which is the sort of wrong answer this command
  // exists to eliminate.
  const stages = checkLicenseStages({
    key: options.key,
    publicKeyPem,
    machineId: options.machine ?? null,
  });

  return {
    ok: result.ok,
    stage: result.stage,
    message: result.message,
    payload: result.payload,
    daysUntilExpiry: result.daysUntilExpiry,
    checks: [
      {
        name: "format",
        passed: stages.format.passed,
        detail: stages.format.passed
          ? "two base64 segments separated by a dot, payload is JSON"
          : "not two base64 segments separated by a dot, or the payload is not a licence",
      },
      {
        name: "signature",
        passed: stages.signature.passed,
        detail: stages.signature.passed
          ? "signature matches the public key embedded in the app"
          : "signature does not match the embedded public key",
      },
      {
        name: "machineId",
        passed: stages.machineId.passed,
        detail:
          options.machine === undefined
            ? "not checked (pass --machine to check it)"
            : stages.machineId.passed
              ? "key is bound to the given machine"
              : "key is bound to a different machine",
      },
      {
        name: "expiry",
        passed: stages.expiry.passed,
        detail: stages.expiry.passed
          ? stages.expiry.daysUntilExpiry === null
            ? "perpetual, no expiry"
            : `valid for ${stages.expiry.daysUntilExpiry} more day(s)`
          : "key has expired",
      },
    ],
  };
}

/** Read a key's payload without checking anything about it. */
export function inspectLicenseKey(key: string): LicensePayload {
  const parts = splitLicenseKey(key);
  if (parts === null) throw new Error("Invalid key format");
  return decodeLicensePayload(parts.payloadSegment);
}
